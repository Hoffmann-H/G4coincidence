PrimaryGeneratorAction::PrimaryGeneratorAction()
 : G4VUserPrimaryGeneratorAction(),
   fParticleGun(0)
{
  G4int n_particle = 1;
  fParticleGun  = new G4ParticleGun(n_particle);

  fParticleGun->SetParticleEnergy(0*eV);
  fParticleGun->SetParticlePosition(G4ThreeVector(0.,0.,0.));
  fParticleGun->SetParticleMomentumDirection(G4ThreeVector(1.,0.,0.));
}

//....oooOO0OOooo........oooOO0OOooo........oooOO0OOooo........oooOO0OOooo......

PrimaryGeneratorAction::~PrimaryGeneratorAction()
{
  delete fParticleGun;
}

//....oooOO0OOooo........oooOO0OOooo........oooOO0OOooo........oooOO0OOooo......

void PrimaryGeneratorAction::GeneratePrimaries(G4Event* anEvent)
{
  if (fParticleGun->GetParticleDefinition() == G4Geantino::Geantino()) {  
    //G4cout << "DEBUG: Setting particle gun from Geantino to Z = 10, A = 24" << G4endl;
    G4int Z = 11, A = 24;
    G4double ionCharge   = 0.*eplus;
    G4double excitEnergy = 0.*keV;
    
    G4ParticleDefinition* ion
       = G4IonTable::GetIonTable()->GetIon(Z,A,excitEnergy);
    fParticleGun->SetParticleDefinition(ion);
    fParticleGun->SetParticleCharge(ionCharge);
  }

  G4double sample_cz = 10.0*cm; // sample center z
  G4double sample_r = 0;        // sample radius
  G4double sample_dz = 0;       // sample total z thickness

  G4double random_r = sample_r * sqrt(G4UniformRand());
  G4double random_phi = 2*M_PI*G4UniformRand();
  G4double random_z = sample_dz * (G4UniformRand()-0.5);
  G4double x0 = random_r * cos(random_phi);
  G4double y0 = random_r * sin(random_phi);
  G4double z0 = sample_cz + random_z;

  //G4cout << "particle position: " << x0 << "," << y0 << "," << z0 << G4endl;  
  
  fParticleGun->SetParticlePosition(G4ThreeVector(x0,y0,z0));

  //create vertex
  //   
  fParticleGun->GeneratePrimaryVertex(anEvent);
}
